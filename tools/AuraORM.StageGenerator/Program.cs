// Writes the SELECT stage types of docs/design.ja.md §5.1 that differ only by the number of tables (MaxSources) and the
// number of tuple elements (MaxTuple). The output goes to src/AuraORM/Select/Generated and is committed; CI runs this
// program and CSharpier, and fails when the result differs from the commit.
using System.Globalization;
using System.Text;

const int MaxSources = 1; // Row Q2 (JOIN) raises it to 8.
const int MaxTuple = 8;

string root = FindRoot();
string output = Path.Combine(root, "src", "AuraORM", "Select", "Generated");
Directory.CreateDirectory(output);

Write("SelectSource.cs", SelectSource);
Write("SelectFrom.cs", SelectFrom);
Write("SelectWhere.cs", SelectWhere);
Write("SelectProjected.cs", SelectProjected);
Write("TupleProjection.cs", TupleProjection);
return 0;

void Write(string file, Action<StringBuilder> emit)
{
    var text = new StringBuilder();
    text.Append("// Generated by tools/AuraORM.StageGenerator. Do not edit; run: dotnet run --project tools/AuraORM.StageGenerator\n\n");
    text.Append("namespace AuraORM;\n");
    emit(text);
    File.WriteAllText(Path.Combine(output, file), text.ToString().Replace("\r\n", "\n", StringComparison.Ordinal));
}

void SelectSource(StringBuilder s)
{
    for (int n = 1; n <= MaxSources; n++)
    {
        string views = Views(n);
        s.Append(
            CultureInfo.InvariantCulture,
            $$"""

            /// <summary>
            /// The sources of a SELECT statement with {{Tables(n)}}, before its projection. The lambdas of the stage get the column set
            /// of each table (<c>docs/design.ja.md</c> §5.1).
            /// </summary>
            /// <typeparam name="TDialect">The SQL dialect.</typeparam>
            {{ViewDocs(n)}}
            public abstract class SelectSource<TDialect, {{views}}>
                where TDialect : IDialect
            {
                private protected SelectSource(IStatementRunner session, SelectState state, {{ViewParameters(n)}})
                {
                    Session = session;
                    State = state;
            {{Lines(n, i => $"        V{i} = v{i};")}}
                }

                private protected IStatementRunner Session { get; }

                private protected SelectState State { get; }

            {{Lines(n, i => $"    private protected T{i} V{i} {{ get; }}", "\n\n")}}

            """
        );
        foreach (bool distinct in new[] { false, true })
        {
            string method = distinct ? "SelectDistinct" : "Select";
            string sql = distinct ? "SELECT DISTINCT" : "SELECT";
            s.Append(
                CultureInfo.InvariantCulture,
                $$"""

                    /// <summary>
                    /// Sets the projection: <c>{{sql}} …</c>. The projection is a column, an expression, a whole row, or a result
                    /// type's projection, all of one evaluation level (<c>docs/design.ja.md</c> §5.6). A <see cref="PerGroup"/>
                    /// projection aggregates the whole table as one group.
                    /// </summary>
                    /// <typeparam name="TResult">The type that each row is read as.</typeparam>
                    /// <typeparam name="TLevel">The evaluation level of the projection.</typeparam>
                    /// <param name="projection">The projection, from the column sets.</param>
                    /// <returns>The statement.</returns>
                    public SelectProjected<TDialect, TResult, TLevel, {{views}}> {{method}}<TResult, TLevel>(Func<{{views}}, IProjection<TResult, TLevel>> projection)
                        where TLevel : EvaluationLevel
                    {
                        ArgumentNullException.ThrowIfNull(projection);
                        return Project(projection({{Args(n)}}), distinct: {{(distinct ? "true" : "false")}});
                    }

                """
            );
            for (int k = 2; k <= MaxTuple; k++)
            {
                string results = string.Join(", ", Enumerable.Range(1, k).Select(i => $"TItem{i}"));
                string tuple = "(" + string.Join(", ", Enumerable.Range(1, k).Select(i => $"IProjection<TItem{i}, TLevel>")) + ")";
                s.Append(
                    CultureInfo.InvariantCulture,
                    $$"""

                    /// <summary>
                    /// Sets the projection as a tuple of {{k}} items: <c>{{sql}} a, b, …</c>. Every item has the same evaluation level
                    /// (<c>docs/design.ja.md</c> §5.6).
                    /// </summary>
                    {{Lines(k, i => $"    /// <typeparam name=\"TItem{i}\">The type of item {i}.</typeparam>")}}
                        /// <typeparam name="TLevel">The evaluation level of every item.</typeparam>
                        /// <param name="projection">The items, from the column sets.</param>
                        /// <returns>The statement.</returns>
                        public SelectProjected<TDialect, ({{results}}), TLevel, {{views}}> {{method}}<{{results}}, TLevel>(Func<{{views}}, {{tuple}}> projection)
                            where TLevel : EvaluationLevel
                        {
                            ArgumentNullException.ThrowIfNull(projection);
                            {{tuple}} items = projection({{Args(n)}});
                            return Project(new TupleProjection<{{results}}, TLevel>({{string.Join(
                        ", ",
                        Enumerable.Range(1, k).Select(i => $"items.Item{i}")
                    )}}), distinct: {{(distinct ? "true" : "false")}});
                        }

                    """
                );
            }
        }

        s.Append(
            CultureInfo.InvariantCulture,
            $$"""

                private SelectProjected<TDialect, TResult, TLevel, {{views}}> Project<TResult, TLevel>(IProjection<TResult, TLevel> projection, bool distinct)
                    where TLevel : EvaluationLevel => new(Session, State.WithProjection(projection, distinct), projection, {{Args(n)}});
            }

            """
        );
    }
}

void SelectFrom(StringBuilder s)
{
    for (int n = 1; n <= MaxSources; n++)
    {
        string pairs = string.Join(", ", Enumerable.Range(1, n).Select(i => $"T{i}, TNullable{i}"));
        string pairDocs = Lines(
            n,
            i =>
                $"/// <typeparam name=\"T{i}\">The column set of table {i}, as the lambdas get it now.</typeparam>\n"
                + $"/// <typeparam name=\"TNullable{i}\">The column set of table {i} on the nullable side of an outer join.</typeparam>"
        );
        s.Append(
            CultureInfo.InvariantCulture,
            $$"""

            /// <summary>
            /// A SELECT statement right after <c>FROM</c>, with {{Tables(n)}} (<c>docs/design.ja.md</c> §5.1). <c>WHERE</c> may follow once.
            /// </summary>
            /// <typeparam name="TDialect">The SQL dialect.</typeparam>
            {{pairDocs}}
            public sealed class SelectFrom<TDialect, {{pairs}}> : SelectSource<TDialect, {{Views(n)}}>
                where TDialect : IDialect
            {
                internal SelectFrom(IStatementRunner session, SelectState state, {{ViewParameters(n)}})
                    : base(session, state, {{Lower(n)}}) { }

                /// <summary>
                /// Adds the condition: <c>WHERE condition</c>. To combine conditions, write <see cref="Sql.And{TLevel}(Condition{TLevel}, Condition{TLevel}, Condition{TLevel}[])"/>.
                /// </summary>
                /// <param name="condition">The condition, from the column sets.</param>
                /// <returns>The statement.</returns>
                public SelectWhere<TDialect, {{Views(n)}}> Where(Func<{{Views(n)}}, Condition<PerRow>> condition)
                {
                    ArgumentNullException.ThrowIfNull(condition);
                    return new(Session, State with { Where = condition({{Args(n)}}).Node }, {{Args(n)}});
                }
            }

            """
        );
    }
}

void SelectWhere(StringBuilder s)
{
    for (int n = 1; n <= MaxSources; n++)
    {
        s.Append(
            CultureInfo.InvariantCulture,
            $$"""

            /// <summary>
            /// A SELECT statement after <c>WHERE</c>, with {{Tables(n)}} (<c>docs/design.ja.md</c> §5.1).
            /// </summary>
            /// <typeparam name="TDialect">The SQL dialect.</typeparam>
            {{ViewDocs(n)}}
            public sealed class SelectWhere<TDialect, {{Views(n)}}> : SelectSource<TDialect, {{Views(n)}}>
                where TDialect : IDialect
            {
                internal SelectWhere(IStatementRunner session, SelectState state, {{ViewParameters(n)}})
                    : base(session, state, {{Lower(n)}}) { }
            }

            """
        );
    }
}

void SelectProjected(StringBuilder s)
{
    for (int n = 1; n <= MaxSources; n++)
    {
        s.Append(
            CultureInfo.InvariantCulture,
            $$"""

            /// <summary>
            /// A SELECT statement right after its projection, with {{Tables(n)}} (<c>docs/design.ja.md</c> §5.1). <c>ORDER BY</c> may
            /// follow once.
            /// </summary>
            /// <typeparam name="TDialect">The SQL dialect.</typeparam>
            /// <typeparam name="TResult">The type that each row is read as.</typeparam>
            /// <typeparam name="TLevel">The evaluation level of the projection.</typeparam>
            {{ViewDocs(n)}}
            public sealed class SelectProjected<TDialect, TResult, TLevel, {{Views(n)}}> : SelectProjection<TDialect, TResult, TLevel>
                where TDialect : IDialect
                where TLevel : EvaluationLevel
            {
            {{Lines(n, i => $"    private readonly T{i} _v{i};", "\n")}}

                internal SelectProjected(IStatementRunner session, SelectState state, IProjection<TResult, TLevel> projection, {{ViewParameters(n)}})
                    : base(session, state, FactoryOf(projection))
                {
            {{Lines(n, i => $"        _v{i} = v{i};")}}
                }

                /// <summary>
                /// Orders the rows: <c>ORDER BY a ASC, b DESC</c> (<c>docs/design.ja.md</c> §5.8). The keys have the level of the
                /// projection.
                /// </summary>
                /// <param name="orderings">The keys, in order, from the column sets: <c>u =&gt; [Asc(u.Name), Desc(u.Id)]</c>.</param>
                /// <returns>The statement.</returns>
                /// <exception cref="ArgumentException">There is no key.</exception>
                public SelectOrdered<TDialect, TResult> OrderBy(Func<{{Views(n)}}, Ordering<TLevel>[]> orderings)
                {
                    ArgumentNullException.ThrowIfNull(orderings);
                    return new(Session, State.WithOrderBy(orderings({{string.Join(", ", Enumerable.Range(1, n).Select(i => $"_v{i}"))}})), Factory);
                }
            }

            """
        );
    }
}

void TupleProjection(StringBuilder s)
{
    for (int k = 2; k <= MaxTuple; k++)
    {
        string results = string.Join(", ", Enumerable.Range(1, k).Select(i => $"TItem{i}"));
        string parameters = string.Join(", ", Enumerable.Range(1, k).Select(i => $"IProjection<TItem{i}, TLevel> p{i}"));
        s.Append(
            CultureInfo.InvariantCulture,
            $$"""

            /// <summary>
            /// The projection of a tuple of {{k}} items: the items' select lists one after another, read in the same order.
            /// </summary>
            {{Lines(k, i => $"/// <typeparam name=\"TItem{i}\">The type of item {i}.</typeparam>")}}
            /// <typeparam name="TLevel">The evaluation level of every item.</typeparam>
            internal sealed class TupleProjection<{{results}}, TLevel>({{parameters}}) : IProjection<({{results}}), TLevel>
                where TLevel : EvaluationLevel
            {
                void IProjection<({{results}}), TLevel>.CollectSelectItems(List<SqlNode> items)
                {
            {{Lines(k, i => $"        p{i}.CollectSelectItems(items);")}}
                }

                ({{results}}) IProjection<({{results}}), TLevel>.Read(ref RowReader reader) => ({{string.Join(
                ", ",
                Enumerable.Range(1, k).Select(i => $"reader.Read(p{i})")
            )}});
            }

            """
        );
    }
}

static string Views(int n) => string.Join(", ", Enumerable.Range(1, n).Select(i => $"T{i}"));

static string Args(int n) => string.Join(", ", Enumerable.Range(1, n).Select(i => $"V{i}"));

static string Lower(int n) => string.Join(", ", Enumerable.Range(1, n).Select(i => $"v{i}"));

static string ViewParameters(int n) => string.Join(", ", Enumerable.Range(1, n).Select(i => $"T{i} v{i}"));

static string ViewDocs(int n) => Lines(n, i => $"/// <typeparam name=\"T{i}\">The column set of table {i}.</typeparam>");

static string Tables(int n) => n == 1 ? "one table" : $"{n} tables";

static string Lines(int n, Func<int, string> line, string separator = "\n") => string.Join(separator, Enumerable.Range(1, n).Select(line));

static string FindRoot()
{
    for (string? directory = AppContext.BaseDirectory; directory is not null; directory = Path.GetDirectoryName(directory))
    {
        if (File.Exists(Path.Combine(directory, "AuraORM.slnx")))
        {
            return directory;
        }
    }

    throw new InvalidOperationException("AuraORM.slnx was not found above " + AppContext.BaseDirectory);
}
