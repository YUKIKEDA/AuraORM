{
    for (int n = 1; n <= MaxSources; n++)
    {
        string views = Views(n);
        s.Append(
            CultureInfo.InvariantCulture,
            $$"""

            /// <summary>
            /// A SELECT statement right after <c>GROUP BY</c>, with {{Tables(n)}} (<c>docs/design.ja.md</c> §5.5). <c>HAVING</c> may
            /// follow once.
            /// </summary>
