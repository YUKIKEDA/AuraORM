void SelectProjected(StringBuilder s)
{
    for (int n = 1; n <= MaxSources; n++)
    {
        s.Append(
            CultureInfo.InvariantCulture,
            $$"""

            /// <summary>
            /// A SELECT statement right after its projection, with {{Tables(n)}} (<c>docs/design.ja.md</c> §5.1). <c>ORDER BY</c> may
            /// follow once.
            /// </summary>
            /// <typeparam name="TDialect">The SQL dialect.</typeparam>
            /// <typeparam name="TMode">Whether the statement can be run: <see cref="Executable"/> or <see cref="SqlOnly"/>.</typeparam>
            /// <typeparam name="TResult">The type that each row is read as.</typeparam>
            /// <typeparam name="TLevel">The evaluation level of the projection.</typeparam>
            {{ViewDocs(n)}}
            public sealed class SelectProjected<TDialect, TMode, TResult, TLevel, {{Views(n)}}> : SelectProjection<TDialect, TMode, TResult, TLevel>
                where TDialect : IDialect
                where TMode : ExecutionMode
                where TLevel : EvaluationLevel
            {
            {{Lines(n, i => $"    private readonly T{i} _v{i};", "\n")}}

                internal SelectProjected(IStatementRunner? session, SelectState state, IProjection<TResult, TLevel> projection, {{ViewParameters(n)}})
                    : base(session, state, FactoryOf(projection))
                {
            {{Lines(n, i => $"        _v{i} = v{i};")}}
                }

                /// <summary>
                /// Orders the rows: <c>ORDER BY a ASC, b DESC</c> (<c>docs/design.ja.md</c> §5.8). The keys have the level of the
                /// projection.
                /// </summary>
                /// <param name="orderings">The keys, in order, from the column sets: <c>u =&gt; [Asc(u.Name), Desc(u.Id)]</c>.</param>
                /// <returns>The statement.</returns>
                /// <exception cref="ArgumentException">There is no key.</exception>
                public SelectOrdered<TDialect, TMode, TResult> OrderBy(Func<{{Views(n)}}, Ordering<TLevel>[]> orderings)
                {
                    ArgumentNullException.ThrowIfNull(orderings);
                    return new(Session, State.WithOrderBy(orderings({{string.Join(", ", Enumerable.Range(1, n).Select(i => $"_v{i}"))}})), Factory);
                }
            }

            """
        );
    }
}

void TupleProjection(StringBuilder s)
{
    for (int k = 2; k <= MaxTuple; k++)
    {
        string results = string.Join(", ", Enumerable.Range(1, k).Select(i => $"TItem{i}"));
        string parameters = string.Join(", ", Enumerable.Range(1, k).Select(i => $"IProjection<TItem{i}, TLevel> p{i}"));
        s.Append(
            CultureInfo.InvariantCulture,
            $$"""

            /// <summary>
            /// The projection of a tuple of {{k}} items: the items' select lists one after another, read in the same order.
            /// </summary>
            {{Lines(k, i => $"/// <typeparam name=\"TItem{i}\">The type of item {i}.</typeparam>")}}
            /// <typeparam name="TLevel">The evaluation level of every item.</typeparam>
            internal sealed class TupleProjection<{{results}}, TLevel>({{parameters}}) : IProjection<({{results}}), TLevel>
                where TLevel : EvaluationLevel
            {
                void IProjection<({{results}}), TLevel>.CollectSelectItems(List<SqlNode> items)
                {
            {{Lines(k, i => $"        p{i}.CollectSelectItems(items);")}}
                }

                ({{results}}) IProjection<({{results}}), TLevel>.Read(ref RowReader reader) => ({{string.Join(
                ", ",
                Enumerable.Range(1, k).Select(i => $"reader.Read(p{i})")
            )}});
            }

            """
        );
    }
}

static string Pairs(int n) => string.Join(", ", Enumerable.Range(1, n).Select(i => $"T{i}, TNullable{i}"));

static string NullablePairs(int n) => string.Join(", ", Enumerable.Range(1, n).Select(i => $"TNullable{i}, TNullable{i}"));

static string PairDocs(int n) =>
    string.Concat(
        Enumerable
            .Range(1, n)
            .Select(i =>
                $"/// <typeparam name=\"T{i}\">The column set of table {i}, as the lambdas get it now.</typeparam>\n"
                + $"/// <typeparam name=\"TNullable{i}\">The column set of table {i} on the nullable side of an outer join.</typeparam>\n"
            )
    );

static string NullableConstraints(int n, string indent) =>
    string.Concat(Enumerable.Range(1, n).Select(i => $"{indent}where TNullable{i} : ITableColumns<TNullable{i}>\n"));

static string Views(int n) => string.Join(", ", Enumerable.Range(1, n).Select(i => $"T{i}"));

static string Args(int n) => string.Join(", ", Enumerable.Range(1, n).Select(i => $"V{i}"));

static string Lower(int n) => string.Join(", ", Enumerable.Range(1, n).Select(i => $"v{i}"));

static string ViewParameters(int n) => string.Join(", ", Enumerable.Range(1, n).Select(i => $"T{i} v{i}"));

static string ViewDocs(int n) => Lines(n, i => $"/// <typeparam name=\"T{i}\">The column set of table {i}.</typeparam>");

static string Tables(int n) => n == 1 ? "one table" : $"{n} tables";

static string Lines(int n, Func<int, string> line, string separator = "\n") => string.Join(separator, Enumerable.Range(1, n).Select(line));

static string FindRoot()
{
    for (string? directory = AppContext.BaseDirectory; directory is not null; directory = Path.GetDirectoryName(directory))
    {
        if (File.Exists(Path.Combine(directory, "AuraORM.slnx")))
        {
            return directory;
        }
    }

    throw new InvalidOperationException("AuraORM.slnx was not found above " + AppContext.BaseDirectory);
}
