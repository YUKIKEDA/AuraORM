void MutationReturning(StringBuilder s)
{
    (string Statement, string Capability, string Sql)[] kinds =
    [
        ("InsertStatement", "IInsertReturningDialect", "INSERT"),
        ("UpdateStatement", "IUpdateReturningDialect", "UPDATE"),
        ("DeleteStatement", "IDeleteReturningDialect", "DELETE"),
        ("UpsertStatement", "IInsertReturningDialect", "upsert"),
    ];
    s.Append(
        """

        /// <summary>
        /// The <c>Returning</c> of <c>INSERT</c>, <c>UPDATE</c>, and <c>DELETE</c> (<c>docs/design.ja.md</c> §9): the statement returns
        /// the values of the rows it changed. Each method exists only for a dialect that can return them
        /// (<see cref="IInsertReturningDialect"/>, <see cref="IUpdateReturningDialect"/>, <see cref="IDeleteReturningDialect"/>), so
        /// it does not compile on the others (MySQL; MariaDB's <c>UPDATE</c>).
        /// </summary>
        /// <remarks>
        /// The projection is that of a SELECT (§5.6): a column, an expression, the whole row, a result type's projection, or a tuple
        /// of them, of <see cref="PerRow"/> values only. Its columns are written unqualified (SQL Server: <c>INSERTED.</c> or
        /// <c>DELETED.</c>). For <c>UPDATE</c> they are the new values, for <c>DELETE</c> the deleted ones. A subquery that reads the
        /// table being changed, and any subquery on SQL Server, make the statement throw <see cref="InvalidOperationException"/>
        /// when it is rendered (§9, §14.3).
        /// </remarks>
        public static class MutationReturning
        {
        """
    );
    foreach ((string statement, string capability, string sql) in kinds)
    {
        s.Append(
            CultureInfo.InvariantCulture,
            $$"""

                /// <summary>
                /// Returns the values of the rows that the {{sql}} changed: <c>RETURNING …</c> (SQL Server: <c>OUTPUT …</c>).
                /// </summary>
                /// <typeparam name="TDialect">The SQL dialect.</typeparam>
                /// <typeparam name="TMode">Whether the statement can be run.</typeparam>
                /// <typeparam name="TColumns">The column set of the table.</typeparam>
                /// <typeparam name="TResult">The type that each row is read as.</typeparam>
                /// <param name="statement">The statement.</param>
                /// <param name="projection">The projection, from the columns of the table.</param>
                /// <returns>The statement, which returns rows.</returns>
                public static ReturningQuery<TDialect, TMode, TResult> Returning<TDialect, TMode, TColumns, TResult>(
                    this {{statement}}<TDialect, TMode, TColumns> statement,
                    Func<TColumns, IProjection<TResult, PerRow>> projection
                )
                    where TDialect : {{capability}}
                    where TMode : ExecutionMode
                    where TColumns : ITableColumns<TColumns>
                {
                    ArgumentNullException.ThrowIfNull(statement);
                    ArgumentNullException.ThrowIfNull(projection);
                    return new(statement, projection(statement.Table));
                }

            """
        );
        for (int k = 2; k <= MaxTuple; k++)
        {
            string results = string.Join(", ", Enumerable.Range(1, k).Select(i => $"TItem{i}"));
            string items = string.Join(", ", Enumerable.Range(1, k).Select(i => $"IProjection<TItem{i}, PerRow>"));
            string arguments = string.Join(", ", Enumerable.Range(1, k).Select(i => $"items.Item{i}"));
            s.Append(
                CultureInfo.InvariantCulture,
                $$"""

                    /// <summary>
                    /// Returns the values of the rows that the {{sql}} changed, as a tuple of {{k}} items: <c>RETURNING a, b, …</c>.
                    /// </summary>
                    /// <typeparam name="TDialect">The SQL dialect.</typeparam>
                    /// <typeparam name="TMode">Whether the statement can be run.</typeparam>
                    /// <typeparam name="TColumns">The column set of the table.</typeparam>
                {{Lines(k, i => $"    /// <typeparam name=\"TItem{i}\">The type of item {i}.</typeparam>")}}
                    /// <param name="statement">The statement.</param>
                    /// <param name="projection">The items, from the columns of the table.</param>
                    /// <returns>The statement, which returns rows.</returns>
                    public static ReturningQuery<TDialect, TMode, ({{results}})> Returning<TDialect, TMode, TColumns, {{results}}>(
                        this {{statement}}<TDialect, TMode, TColumns> statement,
                        Func<TColumns, ({{items}})> projection
                    )
                        where TDialect : {{capability}}
                        where TMode : ExecutionMode
                        where TColumns : ITableColumns<TColumns>
                    {
                        ArgumentNullException.ThrowIfNull(statement);
                        ArgumentNullException.ThrowIfNull(projection);
                        ({{items}}) items = projection(statement.Table);
                        return new(statement, new TupleProjection<{{results}}, PerRow>({{arguments}}));
                    }

                """
            );
        }
    }

    s.Append("}\n");
}

void SelectCombinationOrdering(StringBuilder s)
{
    s.Append(
        """

        /// <summary>
        /// <c>OrderBy</c> after a set operation (<c>docs/design.ja.md</c> §5.10): the lambda gets an item for each element of the
        /// result type, and each key names its item by its position (<c>ORDER BY 1 ASC</c>), because each operand selects the
        /// item from its own tables. A projection that holds a whole row or a result type throws, because its items have no
        /// positions.
        /// </summary>
        public static class SelectCombinationOrdering
        {
            /// <summary>
            /// Orders the result of a set operation of one expression: <c>ORDER BY 1 ASC</c>.
            /// </summary>
            /// <typeparam name="TDialect">The SQL dialect.</typeparam>
            /// <typeparam name="TMode">Whether the statement can be run.</typeparam>
            /// <typeparam name="TResult">The type of the item.</typeparam>
            /// <typeparam name="TLevel">The evaluation level of the first statement's projection.</typeparam>
            /// <param name="combination">The set operation.</param>
            /// <param name="orderings">The keys, in order, from the item: <c>s =&gt; [Desc(s)]</c>.</param>
            /// <returns>The statement.</returns>
            /// <exception cref="ArgumentException">There is no key.</exception>
            /// <exception cref="InvalidOperationException">The projection is a whole row or a result type.</exception>
            public static SelectOrdered<TDialect, TMode, TResult> OrderBy<TDialect, TMode, TResult, TLevel>(
                this SelectCombination<TDialect, TMode, TResult, TLevel> combination,
                Func<SetItem<TResult, TLevel>, Ordering<TLevel>[]> orderings
            )
                where TDialect : IDialect
                where TMode : ExecutionMode
                where TLevel : EvaluationLevel
            {
                ArgumentNullException.ThrowIfNull(combination);
                ArgumentNullException.ThrowIfNull(orderings);
                return combination.OrderByCore(orderings(new SetItem<TResult, TLevel>(1)));
            }

        """
    );
    for (int k = 2; k <= MaxTuple; k++)
    {
        string results = string.Join(", ", Enumerable.Range(1, k).Select(i => $"TItem{i}"));
        string items = "(" + string.Join(", ", Enumerable.Range(1, k).Select(i => $"SetItem<TItem{i}, TLevel>")) + ")";
        string created = "(" + string.Join(", ", Enumerable.Range(1, k).Select(i => $"new SetItem<TItem{i}, TLevel>({i})")) + ")";
        s.Append(
            CultureInfo.InvariantCulture,
            $$"""

                /// <summary>
                /// Orders the result of a set operation of a tuple of {{k}} items: <c>ORDER BY 1 ASC, 2 DESC</c>.
                /// </summary>
                /// <typeparam name="TDialect">The SQL dialect.</typeparam>
                /// <typeparam name="TMode">Whether the statement can be run.</typeparam>
            {{Lines(k, i => $"    /// <typeparam name=\"TItem{i}\">The type of item {i}.</typeparam>")}}
                /// <typeparam name="TLevel">The evaluation level of the first statement's projection.</typeparam>
                /// <param name="combination">The set operation.</param>
                /// <param name="orderings">The keys, in order, from the items: <c>s =&gt; [Asc(s.Item1), Desc(s.Item2)]</c>.</param>
                /// <returns>The statement.</returns>
                /// <exception cref="ArgumentException">There is no key.</exception>
                /// <exception cref="InvalidOperationException">An item is a whole row or a result type.</exception>
                public static SelectOrdered<TDialect, TMode, ({{results}})> OrderBy<TDialect, TMode, {{results}}, TLevel>(
                    this SelectCombination<TDialect, TMode, ({{results}}), TLevel> combination,
                    Func<{{items}}, Ordering<TLevel>[]> orderings
                )
                    where TDialect : IDialect
                    where TMode : ExecutionMode
                    where TLevel : EvaluationLevel
                {
                    ArgumentNullException.ThrowIfNull(combination);
                    ArgumentNullException.ThrowIfNull(orderings);
                    return combination.OrderByCore(orderings({{created}}));
                }

            """
        );
    }

    s.Append("}\n");
}

static string Pairs(int n) => string.Join(", ", Enumerable.Range(1, n).Select(i => $"T{i}, TNullable{i}"));

static string NullablePairs(int n) => string.Join(", ", Enumerable.Range(1, n).Select(i => $"TNullable{i}, TNullable{i}"));

static string PairDocs(int n) =>
    string.Concat(
        Enumerable
            .Range(1, n)
            .Select(i =>
                $"/// <typeparam name=\"T{i}\">The column set of table {i}, as the lambdas get it now.</typeparam>\n"
                + $"/// <typeparam name=\"TNullable{i}\">The column set of table {i} on the nullable side of an outer join.</typeparam>\n"
            )
    );

static string NullableConstraints(int n, string indent) =>
    string.Concat(Enumerable.Range(1, n).Select(i => $"{indent}where TNullable{i} : ITableColumns<TNullable{i}>\n"));

static string Views(int n) => string.Join(", ", Enumerable.Range(1, n).Select(i => $"T{i}"));

static string Args(int n) => string.Join(", ", Enumerable.Range(1, n).Select(i => $"V{i}"));

static string Lower(int n) => string.Join(", ", Enumerable.Range(1, n).Select(i => $"v{i}"));

static string ViewParameters(int n) => string.Join(", ", Enumerable.Range(1, n).Select(i => $"T{i} v{i}"));

static string ViewDocs(int n) => Lines(n, i => $"/// <typeparam name=\"T{i}\">The column set of table {i}.</typeparam>");

static string Tables(int n) => n == 1 ? "one table" : $"{n} tables";

static string Lines(int n, Func<int, string> line, string separator = "\n") => string.Join(separator, Enumerable.Range(1, n).Select(line));

static string FindRoot()
{
    for (string? directory = AppContext.BaseDirectory; directory is not null; directory = Path.GetDirectoryName(directory))
    {
        if (File.Exists(Path.Combine(directory, "AuraORM.slnx")))
        {
            return directory;
        }
    }

    throw new InvalidOperationException("AuraORM.slnx was not found above " + AppContext.BaseDirectory);
}
