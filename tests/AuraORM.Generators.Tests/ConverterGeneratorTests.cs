namespace AuraORM.Generators.Tests;

public sealed class ConverterGeneratorTests
{
    private const string Usings = """
        using System;
        using AuraORM;

        """;

    private const string UserId = """
        [ValueConverter(typeof(UserIdConverter))]
        public readonly record struct UserId(long Value);

        public sealed class UserIdConverter : IValueConverter<UserId, long>
        {
            public static long ToProvider(UserId value) => value.Value;
            public static UserId FromProvider(long value) => new(value);
        }

        """;

    private const string RegistrationCollision =
        "namespace AuraORM.Generated { internal static class __AuraValueConverters { } }\n"
        + UserId
        + "[Table(\"t\")] public sealed partial record T([PrimaryKey] UserId Id);";

    /// <summary>
    /// A type with a converter is a column and a result member, stored as the converter's provider type, and the generator
    /// registers the converters that the compilation declares or uses in one module initializer (design §3.6).
    /// </summary>
    /// <remarks>
    /// Preconditions:
    /// - <c>UserId</c> with a converter on the type; <c>Uri</c> with a converter on the assembly.
    ///
    /// Steps:
    /// - Run the generator on a table with a <c>UserId</c> key, a <c>UserId?</c> column, and a <c>Uri?</c> column, and on a
    ///   result type with a <c>UserId</c> member; compile.
    ///
    /// Expected:
    /// - No diagnostic.
    /// - The table's <c>ColumnInfo</c> of the key has the provider type <c>Int64</c>.
    /// - <c>AuraORM.Generated.__AuraValueConverters</c> registers <c>UserId</c> with <c>RegisterStruct</c> and <c>Uri</c> with
    ///   <c>RegisterClass</c>, each once, in a <c>[ModuleInitializer]</c> of an auto-generated file.
    /// </remarks>
    [Fact]
    public void Converter_OnTypeAndAssembly_IsAColumnAndIsRegistered()
    {
        IReadOnlyDictionary<string, string> sources = GeneratorHarness.Compiles(
            Usings
                + "[assembly: ValueConverter(typeof(UriConverter))]\n"
                + UserId
                + """
                public sealed class UriConverter : IValueConverter<Uri, string>
                {
                    public static string ToProvider(Uri value) => value.ToString();
                    public static Uri FromProvider(string value) => new(value);
                }

                [Table("users")]
                public sealed partial record User([PrimaryKey] UserId Id, UserId? Parent, Uri? Home);

                [QueryResult]
                public sealed partial record Owner(UserId Id, string Name);
                """
        );

        Assert.Contains(sources.Values, s => s.Contains("new(\"Id\", global::AuraORM.ColumnType.Int64)", StringComparison.Ordinal));
        string registration = sources["AuraORM.Generated.__AuraValueConverters.g.cs"];
        Assert.StartsWith("// <auto-generated/>", registration, StringComparison.Ordinal);
        Assert.Contains("[global::System.Runtime.CompilerServices.ModuleInitializer]", registration, StringComparison.Ordinal);
        Assert.Single(
            registration.Split('\n'),
            l => l.Contains("RegisterStruct<global::UserId, long, global::UserIdConverter>();", StringComparison.Ordinal)
        );
        Assert.Single(
            registration.Split('\n'),
            l => l.Contains("RegisterClass<global::System.Uri, string, global::UriConverter>();", StringComparison.Ordinal)
        );
    }

    /// <summary>
    /// A compilation without converters gets no registration class (design §3.6).
    /// </summary>
    /// <remarks>
    /// Preconditions:
    /// - A table of column types of §3.3 only.
    ///
    /// Steps:
    /// - Run the generator.
    ///
    /// Expected:
    /// - No source named <c>AuraORM.Generated.__AuraValueConverters.g.cs</c>.
    /// </remarks>
    [Fact]
    public void NoConverter_EmitsNoRegistration()
    {
        IReadOnlyDictionary<string, string> sources = GeneratorHarness.Compiles(
            Usings + """[Table("t")] public sealed partial record T([PrimaryKey] long Id);"""
        );

        Assert.DoesNotContain("AuraORM.Generated.__AuraValueConverters.g.cs", sources.Keys);
    }

    /// <summary>
    /// An invalid converter is AURA0105, a type with two converters AURA0115, a type of the registration class's name
    /// AURA0116, and a type without a converter AURA0103 (design §3.6, §15).
    /// </summary>
    /// <remarks>
    /// Preconditions:
    /// - Declarations of the test case.
    ///
    /// Steps:
    /// - Run the generator and compile.
    ///
    /// Expected:
    /// - The diagnostic of the test case, and no other.
    /// </remarks>
    /// <param name="id">The expected diagnostic.</param>
    /// <param name="declaration">The declarations.</param>
    [Theory]
    [InlineData("AURA0105", """[ValueConverter(typeof(string))] public readonly record struct A(long Value);""")]
    [InlineData(
        "AURA0105",
        """[ValueConverter(typeof(BConverter))] public readonly record struct A(long Value); public readonly record struct B(long Value); public sealed class BConverter : IValueConverter<B, long> { public static long ToProvider(B v) => v.Value; public static B FromProvider(long v) => new(v); }"""
    )]
    [InlineData(
        "AURA0105",
        """public enum E { X } [ValueConverter(typeof(AConverter))] public readonly record struct A(E Value); public sealed class AConverter : IValueConverter<A, E> { public static E ToProvider(A v) => v.Value; public static A FromProvider(E v) => new(v); }"""
    )]
    [InlineData(
        "AURA0105",
        """[assembly: ValueConverter(typeof(SConverter))] public sealed class SConverter : IValueConverter<string, int> { public static int ToProvider(string v) => v.Length; public static string FromProvider(int v) => ""; }"""
    )]
    [InlineData(
        "AURA0115",
        """[assembly: ValueConverter(typeof(A2Converter))] [ValueConverter(typeof(AConverter))] public readonly record struct A(long Value); public sealed class AConverter : IValueConverter<A, long> { public static long ToProvider(A v) => v.Value; public static A FromProvider(long v) => new(v); } public sealed class A2Converter : IValueConverter<A, string> { public static string ToProvider(A v) => ""; public static A FromProvider(string v) => new(0); }"""
    )]
    [InlineData(
        "AURA0105",
        """[ValueConverter(typeof(AConverter))] public readonly record struct A(long Value); public sealed class AConverter : IValueConverter<A, long>, IValueConverter<A, string> { static long IValueConverter<A, long>.ToProvider(A v) => v.Value; static A IValueConverter<A, long>.FromProvider(long v) => new(v); static string IValueConverter<A, string>.ToProvider(A v) => ""; static A IValueConverter<A, string>.FromProvider(string v) => new(0); }"""
    )]
    [InlineData("AURA0116", RegistrationCollision)]
    [InlineData(
        "AURA0105",
        """public static class Outer { [ValueConverter(typeof(AConverter))] public readonly record struct A(long Value); private sealed class AConverter : IValueConverter<A, long> { public static long ToProvider(A v) => v.Value; public static A FromProvider(long v) => new(v); } }"""
    )]
    [InlineData(
        "AURA0103",
        """public readonly record struct A(long Value); [Table("t")] public sealed partial record T([PrimaryKey] long Id, A Other);"""
    )]
    public void Converter_Invalid_ReportsDiagnostic(string id, string declaration)
    {
        GeneratorHarness.Fails(Usings + declaration, id);
    }

    /// <summary>
    /// A nullable provider type is AURA0105, besides the warning of the interface's <c>notnull</c> constraint (CS8714) that a
    /// project which does not treat warnings as errors may let through (design §3.6).
    /// </summary>
    /// <remarks>
    /// Preconditions:
    /// - A converter of <c>A</c> to <c>long?</c>.
    ///
    /// Steps:
    /// - Run the generator and compile.
    ///
    /// Expected:
    /// - The error AURA0105 and the warning CS8714.
    /// </remarks>
    [Fact]
    public void Converter_NullableProvider_ReportsAura0105()
    {
        (_, System.Collections.Immutable.ImmutableArray<Microsoft.CodeAnalysis.Diagnostic> diagnostics) = GeneratorHarness.Run(
            Usings
                + """[ValueConverter(typeof(AConverter))] public readonly record struct A(long Value); public sealed class AConverter : IValueConverter<A, long?> { public static long? ToProvider(A v) => v.Value; public static A FromProvider(long? v) => new(v ?? 0); }"""
        );

        Assert.Contains(diagnostics, d => d.Id == "AURA0105" && d.Severity == Microsoft.CodeAnalysis.DiagnosticSeverity.Error);
        Assert.Contains(diagnostics, d => d.Id == "CS8714");
    }
}
