    /// <summary>
    /// <c>CreateIndexes</c> writes one statement per index in declaration order, <c>CREATE UNIQUE INDEX</c> for a unique
    /// one, SQL Server's filter on a nullable column, and <c>IF NOT EXISTS</c> where the dialect has it (design §13.4).
    /// </summary>
    /// <remarks>
    /// Preconditions:
    /// - <see cref="ShopOrder"/>: an index of two columns, and a unique index of a nullable column.
    ///
    /// Steps:
    /// - Render <c>CreateIndexes(ShopOrder.Table)</c> on every dialect, and <c>.IfNotExists()</c> on SQLite,
    ///   PostgreSQL, and MariaDB.
    ///
    /// Expected:
    /// - The two statements of design §13.4 on each dialect, with <c>WHERE [Coupon] IS NOT NULL</c> on SQL Server.
    /// </remarks>
    [Fact]
    public void CreateIndexes_DesignOrder_WritesOneStatementPerIndex()
    {
        Indexes(
            "SQLite",
            [
                "CREATE INDEX \"ix_orders_user\" ON \"orders\" (\"UserId\", \"CreatedAt\")",
                "CREATE UNIQUE INDEX \"ux_orders_coupon\" ON \"orders\" (\"Coupon\")",
            ],
            Sqlite.CreateIndexes(ShopOrder.Table).ToSql()
        );
        Indexes(
            "PostgreSQL",
            [
                "CREATE INDEX \"ix_orders_user\" ON \"orders\" (\"UserId\", \"CreatedAt\")",
                "CREATE UNIQUE INDEX \"ux_orders_coupon\" ON \"orders\" (\"Coupon\")",
            ],
            PostgreSql.CreateIndexes(ShopOrder.Table).ToSql()
        );
        string[] mySql =
        [
            "CREATE INDEX `ix_orders_user` ON `orders` (`UserId`, `CreatedAt`)",
            "CREATE UNIQUE INDEX `ux_orders_coupon` ON `orders` (`Coupon`)",
        ];
        Indexes("MySQL", mySql, MySql.CreateIndexes(ShopOrder.Table).ToSql());
        Indexes("MariaDB", mySql, MariaDb.CreateIndexes(ShopOrder.Table).ToSql());
        Indexes(
            "SQL Server",
            [
                "CREATE INDEX [ix_orders_user] ON [orders] ([UserId], [CreatedAt])",
                "CREATE UNIQUE INDEX [ux_orders_coupon] ON [orders] ([Coupon]) WHERE [Coupon] IS NOT NULL",
            ],
            SqlServer.CreateIndexes(ShopOrder.Table).ToSql()
        );
        Indexes(
            "SQLite",
            [
                "CREATE INDEX IF NOT EXISTS \"ix_orders_user\" ON \"orders\" (\"UserId\", \"CreatedAt\")",
                "CREATE UNIQUE INDEX IF NOT EXISTS \"ux_orders_coupon\" ON \"orders\" (\"Coupon\")",
            ],
            Sqlite.CreateIndexes(ShopOrder.Table).IfNotExists().ToSql()
        );
        Indexes(
            "PostgreSQL",
            [
                "CREATE INDEX IF NOT EXISTS \"ix_orders_user\" ON \"orders\" (\"UserId\", \"CreatedAt\")",
                "CREATE UNIQUE INDEX IF NOT EXISTS \"ux_orders_coupon\" ON \"orders\" (\"Coupon\")",
            ],
            PostgreSql.CreateIndexes(ShopOrder.Table).IfNotExists().ToSql()
        );
        Indexes(
            "MariaDB",
            [
                "CREATE INDEX IF NOT EXISTS `ix_orders_user` ON `orders` (`UserId`, `CreatedAt`)",
                "CREATE UNIQUE INDEX IF NOT EXISTS `ux_orders_coupon` ON `orders` (`Coupon`)",
            ],
            MariaDb.CreateIndexes(ShopOrder.Table).IfNotExists().ToSql()
        );
    }

