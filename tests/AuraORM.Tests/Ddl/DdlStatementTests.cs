        );
        Indexes(
            "SQL Server",
            ["DROP INDEX IF EXISTS [ix_orders_user] ON [orders]", "DROP INDEX IF EXISTS [ux_orders_coupon] ON [orders]"],
            SqlServer.DropIndexes(ShopOrder.Table).IfExists().ToSql()
        );
        Indexes(
            "SQL Server",
            ["DROP INDEX [ix_orders_user] ON [orders]", "DROP INDEX [ux_orders_coupon] ON [orders]"],
            SqlServer.DropIndexes(ShopOrder.Table).ToSql()
        );
        Assert.Empty(Sqlite.DropIndexes(ShopUser.Table).ToSql());
        Assert.Empty(Sqlite.CreateIndexes(ShopUser.Table).ToSql());
    }

    /// <summary>
    /// <c>DROP TABLE</c> and <c>IF EXISTS</c> on every dialect (design §13.8).
    /// </summary>
    /// <remarks>
    /// Preconditions:
    /// - <see cref="ShopOrder"/>.
    ///
    /// Steps:
    /// - Render <c>DropTable(ShopOrder.Table)</c> and <c>.IfExists()</c> on every dialect.
    ///
    /// Expected:
    /// - <c>DROP TABLE "orders"</c> and <c>DROP TABLE IF EXISTS "orders"</c> with each dialect's quotes.
    /// </remarks>
    [Fact]
    public void DropTable_EveryDialect_WritesDropTableAndIfExists()
    {
        SqlAssert.Compare("SQLite", "DROP TABLE \"orders\"", Sqlite.DropTable(ShopOrder.Table).ToSql());
        SqlAssert.Compare("SQLite", "DROP TABLE IF EXISTS \"orders\"", Sqlite.DropTable(ShopOrder.Table).IfExists().ToSql());
        SqlAssert.Compare("PostgreSQL", "DROP TABLE \"orders\"", PostgreSql.DropTable(ShopOrder.Table).ToSql());
        SqlAssert.Compare("PostgreSQL", "DROP TABLE IF EXISTS \"orders\"", PostgreSql.DropTable(ShopOrder.Table).IfExists().ToSql());
        SqlAssert.Compare("MySQL", "DROP TABLE `orders`", MySql.DropTable(ShopOrder.Table).ToSql());
        SqlAssert.Compare("MySQL", "DROP TABLE IF EXISTS `orders`", MySql.DropTable(ShopOrder.Table).IfExists().ToSql());
        SqlAssert.Compare("MariaDB", "DROP TABLE IF EXISTS `orders`", MariaDb.DropTable(ShopOrder.Table).IfExists().ToSql());
        SqlAssert.Compare("SQL Server", "DROP TABLE [orders]", SqlServer.DropTable(ShopOrder.Table).ToSql());
        SqlAssert.Compare("SQL Server", "DROP TABLE IF EXISTS [orders]", SqlServer.DropTable(ShopOrder.Table).IfExists().ToSql());
    }

    /// <summary>
    /// A table in a schema is qualified in every statement, and so is a referenced table in a schema; SQLite qualifies
    /// the index name instead of the table, and PostgreSQL drops the index by its schema (design §13.6).
    /// </summary>
    /// <remarks>
    /// Preconditions:
    /// - <see cref="Audit"/> in <c>app</c>, which references <see cref="ArchivedAccount"/> in <c>archive</c> and has an
    ///   index; <see cref="ArchivedAccount"/> without foreign keys.
    ///
    /// Steps:
    /// - Render <c>CreateTable</c>, <c>CreateIndexes</c>, <c>DropIndexes</c>, and <c>DropTable</c> of
    ///   <see cref="Audit"/> on PostgreSQL, MySQL, and SQL Server; the indexes and <c>CreateTable</c> of
    ///   <see cref="ArchivedAccount"/> on SQLite.
    ///
    /// Expected:
    /// - <c>"app"."audit"</c> and <c>REFERENCES "archive"."accounts"</c>; MySQL's index of the foreign key column.
    /// - SQLite's <c>CREATE INDEX "app"."ix_audit_account" ON "audit"</c> and <c>DROP INDEX "app"."ix_audit_account"</c>.
    /// - PostgreSQL's <c>CREATE INDEX "ix_audit_account" ON "app"."audit"</c> and <c>DROP INDEX "app"."ix_audit_account"</c>.
    /// </remarks>
    [Fact]
    public void Statements_TableInSchema_QualifyTheNames()
    {
        SqlAssert.Compare(
            "PostgreSQL",
            "CREATE TABLE \"app\".\"audit\" (\"Id\" bigint NOT NULL, \"AccountId\" bigint NOT NULL, PRIMARY KEY (\"Id\"), FOREIGN KEY (\"AccountId\") REFERENCES \"archive\".\"accounts\" (\"id\"))",
            PostgreSql.CreateTable(Audit.Table).ToSql()
        );
        SqlAssert.Compare(
            "MySQL",
            "CREATE TABLE `app`.`audit` (`Id` BIGINT NOT NULL, `AccountId` BIGINT NOT NULL, PRIMARY KEY (`Id`), KEY (`AccountId`), FOREIGN KEY (`AccountId`) REFERENCES `archive`.`accounts` (`id`))",
            MySql.CreateTable(Audit.Table).ToSql()
        );
        SqlAssert.Compare(
            "SQL Server",
            "CREATE TABLE [app].[audit] ([Id] bigint NOT NULL, [AccountId] bigint NOT NULL, PRIMARY KEY ([Id]), FOREIGN KEY ([AccountId]) REFERENCES [archive].[accounts] ([id]))",
            SqlServer.CreateTable(Audit.Table).ToSql()
        );
        SqlAssert.Compare(
            "SQLite",
            "CREATE TABLE \"archive\".\"accounts\" (\"id\" INTEGER NOT NULL, \"email\" TEXT NOT NULL, PRIMARY KEY (\"id\"))",
            Sqlite.CreateTable(ArchivedAccount.Table).ToSql()
        );
        Indexes("SQLite", ["CREATE INDEX \"app\".\"ix_audit_account\" ON \"audit\" (\"AccountId\")"], Sqlite.CreateIndexes(Audit.Table).ToSql());
        Indexes("SQLite", ["DROP INDEX \"app\".\"ix_audit_account\""], Sqlite.DropIndexes(Audit.Table).ToSql());
        Indexes(
            "PostgreSQL",
            ["CREATE INDEX \"ix_audit_account\" ON \"app\".\"audit\" (\"AccountId\")"],
            PostgreSql.CreateIndexes(Audit.Table).ToSql()
        );
        Indexes("PostgreSQL", ["DROP INDEX \"app\".\"ix_audit_account\""], PostgreSql.DropIndexes(Audit.Table).ToSql());
        Indexes("MySQL", ["CREATE INDEX `ix_audit_account` ON `app`.`audit` (`AccountId`)"], MySql.CreateIndexes(Audit.Table).ToSql());
        Indexes("MySQL", ["DROP INDEX `ix_audit_account` ON `app`.`audit`"], MySql.DropIndexes(Audit.Table).ToSql());
        Indexes("SQL Server", ["CREATE INDEX [ix_audit_account] ON [app].[audit] ([AccountId])"], SqlServer.CreateIndexes(Audit.Table).ToSql());
        Indexes("SQL Server", ["DROP INDEX [ix_audit_account] ON [app].[audit]"], SqlServer.DropIndexes(Audit.Table).ToSql());
        SqlAssert.Compare("PostgreSQL", "DROP TABLE \"app\".\"audit\"", PostgreSql.DropTable(Audit.Table).ToSql());
        SqlAssert.Compare("SQL Server", "DROP TABLE IF EXISTS [app].[audit]", SqlServer.DropTable(Audit.Table).IfExists().ToSql());
    }

    /// <summary>
    /// A statement made from <see cref="Database{TDialect}"/> renders the same SQL as one from
    /// <see cref="SqlBuilder{TDialect}"/> (design §12.3, §13.1).
    /// </summary>
    /// <remarks>
    /// Preconditions:
    /// - A <see cref="Database{TDialect}"/> of PostgreSQL over a connection that runs nothing.
    ///
    /// Steps:
    /// - Render <c>CreateTable</c>, <c>CreateIndexes</c>, <c>DropIndexes</c>, and <c>DropTable</c> of
    ///   <see cref="ShopOrder"/> from it and from <see cref="SqlBuilder{TDialect}"/>.
    ///
    /// Expected:
    /// - The same text for each.
    /// </remarks>
    [Fact]
    public void Statements_FromDatabase_RenderLikeSqlBuilder()
    {
        var db = new Database<PostgreSqlDialect>(new FakeConnection());
        Assert.Equal(PostgreSql.CreateTable(ShopOrder.Table).ToSql().Text, db.CreateTable(ShopOrder.Table).ToSql().Text);
        Assert.Equal(PostgreSql.DropTable(ShopOrder.Table).ToSql().Text, db.DropTable(ShopOrder.Table).ToSql().Text);
        Assert.Equal(
            PostgreSql.CreateIndexes(ShopOrder.Table).ToSql().Select(s => s.Text),
            db.CreateIndexes(ShopOrder.Table).ToSql().Select(s => s.Text)
        );
        Assert.Equal(
            PostgreSql.DropIndexes(ShopOrder.Table).ToSql().Select(s => s.Text),
            db.DropIndexes(ShopOrder.Table).ToSql().Select(s => s.Text)
        );
    }

    private static void Indexes(string dialect, string[] expected, IReadOnlyList<SqlStatement> statements)
    {
        Assert.True(
            expected.SequenceEqual(statements.Select(s => s.Text)),
            $"{dialect}\nexpected: {string.Join("\n          ", expected)}\nactual:   {string.Join("\n          ", statements.Select(s => s.Text))}"
        );
        Assert.All(statements, s => Assert.Empty(s.Parameters));
    }
