    /// <summary>
    /// <c>CREATE TABLE</c> of the design's <c>orders</c> writes the columns in order, then the primary key, the unique
    /// constraint, MySQL's index of the foreign key column, and the foreign key (design §13.2).
    /// </summary>
    /// <remarks>
    /// Preconditions:
    /// - <see cref="ShopOrder"/>, the <c>Order</c> of design §13.
    ///
    /// Steps:
    /// - Render <c>CreateTable(ShopOrder.Table)</c> on every dialect.
    ///
    /// Expected:
    /// - The SQL of design §13.2, character for character.
    /// </remarks>
    [Fact]
    public void CreateTable_DesignOrder_WritesTheDesignSql()
    {
        SqlAssert.Compare(
            "SQLite",
            "CREATE TABLE \"orders\" (\"Id\" INTEGER PRIMARY KEY AUTOINCREMENT, \"UserId\" INTEGER NOT NULL, \"Code\" TEXT NOT NULL, \"Coupon\" TEXT, \"Total\" TEXT NOT NULL DEFAULT '0.0', \"CreatedAt\" TEXT NOT NULL DEFAULT (strftime('%Y-%m-%d %H:%M:%f', 'now')), UNIQUE (\"Code\"), FOREIGN KEY (\"UserId\") REFERENCES \"users\" (\"Id\"))",
            Sqlite.CreateTable(ShopOrder.Table).ToSql()
        );
        SqlAssert.Compare(
            "PostgreSQL",
            "CREATE TABLE \"orders\" (\"Id\" bigint GENERATED BY DEFAULT AS IDENTITY NOT NULL, \"UserId\" bigint NOT NULL, \"Code\" varchar(20) NOT NULL, \"Coupon\" varchar(20), \"Total\" numeric(18,2) NOT NULL DEFAULT 0, \"CreatedAt\" timestamp NOT NULL DEFAULT (CURRENT_TIMESTAMP AT TIME ZONE 'UTC'), PRIMARY KEY (\"Id\"), UNIQUE (\"Code\"), FOREIGN KEY (\"UserId\") REFERENCES \"users\" (\"Id\"))",
            PostgreSql.CreateTable(ShopOrder.Table).ToSql()
        );
        const string MySqlOrders =
            "CREATE TABLE `orders` (`Id` BIGINT AUTO_INCREMENT NOT NULL, `UserId` BIGINT NOT NULL, `Code` VARCHAR(20) NOT NULL, `Coupon` VARCHAR(20), `Total` DECIMAL(18,2) NOT NULL DEFAULT 0, `CreatedAt` DATETIME(6) NOT NULL DEFAULT (UTC_TIMESTAMP(6)), PRIMARY KEY (`Id`), UNIQUE (`Code`), KEY (`UserId`), FOREIGN KEY (`UserId`) REFERENCES `users` (`Id`))";
        SqlAssert.Compare("MySQL", MySqlOrders, MySql.CreateTable(ShopOrder.Table).ToSql());
        SqlAssert.Compare("MariaDB", MySqlOrders, MariaDb.CreateTable(ShopOrder.Table).ToSql());
        SqlAssert.Compare(
            "SQL Server",
            "CREATE TABLE [orders] ([Id] bigint IDENTITY(1,1) NOT NULL, [UserId] bigint NOT NULL, [Code] nvarchar(20) NOT NULL, [Coupon] nvarchar(20) NULL, [Total] decimal(18,2) NOT NULL DEFAULT 0, [CreatedAt] datetime2 NOT NULL DEFAULT SYSUTCDATETIME(), PRIMARY KEY ([Id]), UNIQUE ([Code]), FOREIGN KEY ([UserId]) REFERENCES [users] ([Id]))",
            SqlServer.CreateTable(ShopOrder.Table).ToSql()
        );
    }

    /// <summary>
    /// <c>CREATE TABLE</c> of the design's <c>users</c> (design §3.1, §13.2), and <c>IfNotExists</c> on the dialects
    /// that have it.
    /// </summary>
    /// <remarks>
    /// Preconditions:
    /// - <see cref="ShopUser"/>, the <c>User</c> of design §3.1.
    ///
    /// Steps:
    /// - Render <c>CreateTable(ShopUser.Table)</c> on every dialect, and <c>.IfNotExists()</c> on SQLite, PostgreSQL,
    ///   MySQL, and MariaDB.
    ///
    /// Expected:
    /// - The auto-increment column of each dialect, the nullable column without <c>NOT NULL</c> (with <c>NULL</c> on SQL
    ///   Server), and the current time in UTC.
    /// - <c>CREATE TABLE IF NOT EXISTS</c> with the same rest.
    /// </remarks>
    [Fact]
    public void CreateTable_DesignUser_WritesEachDialectAndIfNotExists()
    {
        const string SqliteUsers =
            " \"users\" (\"Id\" INTEGER PRIMARY KEY AUTOINCREMENT, \"Name\" TEXT NOT NULL, \"Age\" INTEGER, \"CreatedAt\" TEXT NOT NULL DEFAULT (strftime('%Y-%m-%d %H:%M:%f', 'now')))";
        const string PostgreSqlUsers =
            " \"users\" (\"Id\" bigint GENERATED BY DEFAULT AS IDENTITY NOT NULL, \"Name\" varchar(100) NOT NULL, \"Age\" integer, \"CreatedAt\" timestamp NOT NULL DEFAULT (CURRENT_TIMESTAMP AT TIME ZONE 'UTC'), PRIMARY KEY (\"Id\"))";
        const string MySqlUsers =
            " `users` (`Id` BIGINT AUTO_INCREMENT NOT NULL, `Name` VARCHAR(100) NOT NULL, `Age` INT, `CreatedAt` DATETIME(6) NOT NULL DEFAULT (UTC_TIMESTAMP(6)), PRIMARY KEY (`Id`))";
        SqlAssert.Compare("SQLite", "CREATE TABLE" + SqliteUsers, Sqlite.CreateTable(ShopUser.Table).ToSql());
        SqlAssert.Compare("PostgreSQL", "CREATE TABLE" + PostgreSqlUsers, PostgreSql.CreateTable(ShopUser.Table).ToSql());
        SqlAssert.Compare("MySQL", "CREATE TABLE" + MySqlUsers, MySql.CreateTable(ShopUser.Table).ToSql());
        SqlAssert.Compare("MariaDB", "CREATE TABLE" + MySqlUsers, MariaDb.CreateTable(ShopUser.Table).ToSql());
        SqlAssert.Compare(
            "SQL Server",
            "CREATE TABLE [users] ([Id] bigint IDENTITY(1,1) NOT NULL, [Name] nvarchar(100) NOT NULL, [Age] int NULL, [CreatedAt] datetime2 NOT NULL DEFAULT SYSUTCDATETIME(), PRIMARY KEY ([Id]))",
            SqlServer.CreateTable(ShopUser.Table).ToSql()
        );
        SqlAssert.Compare("SQLite", "CREATE TABLE IF NOT EXISTS" + SqliteUsers, Sqlite.CreateTable(ShopUser.Table).IfNotExists().ToSql());
        SqlAssert.Compare("PostgreSQL", "CREATE TABLE IF NOT EXISTS" + PostgreSqlUsers, PostgreSql.CreateTable(ShopUser.Table).IfNotExists().ToSql());
        SqlAssert.Compare("MySQL", "CREATE TABLE IF NOT EXISTS" + MySqlUsers, MySql.CreateTable(ShopUser.Table).IfNotExists().ToSql());
        SqlAssert.Compare("MariaDB", "CREATE TABLE IF NOT EXISTS" + MySqlUsers, MariaDb.CreateTable(ShopUser.Table).IfNotExists().ToSql());
    }

