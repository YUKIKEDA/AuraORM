using System.Linq;
using System.Text;

using Microsoft.CodeAnalysis;
using Microsoft.CodeAnalysis.CSharp.Syntax;
using Microsoft.CodeAnalysis.Text;

namespace AuraORM.Generator.Query;

/// <summary>
/// InsertQueryValuesのAddメソッドを生成するソースジェネレータ
/// </summary>
[Generator]
public class InsertValuesGenerator : IIncrementalGenerator
{
    private const int MaxColumnCount = 20;
    private const string InsertQueryValuesFullName = "AuraORM.Builder.Query.InsertQueryValues";

    public void Initialize(IncrementalGeneratorInitializationContext context)
    {
        // InsertQueryValuesクラスを検出
        var insertQueryValuesClass = context.SyntaxProvider
            .CreateSyntaxProvider(
                predicate: (node, _) => node is ClassDeclarationSyntax classDecl &&
                    classDecl.Identifier.ValueText == "InsertQueryValues",
                transform: (ctx, ct) => GetInsertQueryValuesInfo(ctx, ct))
            .Where(info => info.HasValue)
            .Select((info, _) => info!.Value);

        // コード生成
        context.RegisterSourceOutput(insertQueryValuesClass, (ctx, exists) =>
        {
            if (exists)
            {
                var source = GenerateSource();
                ctx.AddSource("InsertQueryValues.g.cs", SourceText.From(source, Encoding.UTF8));
            }
        });
    }

    /// <summary>
    /// InsertQueryValuesクラスの情報を取得する
    /// </summary>
    /// <param name="context">シンタックスコンテキスト</param>
    /// <param name="ct">キャンセルトークン</param>
    /// <returns>クラスが存在するかどうか</returns>
    private static bool? GetInsertQueryValuesInfo(GeneratorSyntaxContext context, CancellationToken ct)
    {
        if (context.Node is not ClassDeclarationSyntax classDecl)
        {
            return null;
        }

        var semanticModel = context.SemanticModel;
        var symbol = semanticModel.GetDeclaredSymbol(classDecl, ct);

        if (symbol is not INamedTypeSymbol namedType)
        {
            return null;
        }

        // 完全修飾名が一致するかチェック
        var fullName = namedType.ToDisplayString(SymbolDisplayFormat.FullyQualifiedFormat);
        return fullName.Contains(InsertQueryValuesFullName);
    }

    /// <summary>
    /// ソースコードを生成する
    /// </summary>
    /// <returns>ソースコード</returns>
    private static string GenerateSource()
    {
        var sb = new StringBuilder();

        // ヘッダー
        sb.AppendLine("// <auto-generated />");
        sb.AppendLine("#nullable enable");
        sb.AppendLine();
        sb.AppendLine("using AuraORM.Builder.Table;");
        sb.AppendLine();
        sb.AppendLine("namespace AuraORM.Builder.Query;");
        sb.AppendLine();

        // InsertQueryValuesの部分クラス定義開始
        sb.AppendLine("/// <summary>");
        sb.AppendLine("/// INSERT句の値を表すクラス（生成された部分）");
        sb.AppendLine("/// </summary>");
        sb.AppendLine("public partial class InsertQueryValues");
        sb.AppendLine("{");

        // 各列数に対するAddメソッドを生成
        for (int count = 1; count <= MaxColumnCount; count++)
        {
            GenerateAddMethod(sb, count);
            if (count < MaxColumnCount)
            {
                sb.AppendLine();
            }
        }

        // クラス終了
        sb.AppendLine("}");

        return sb.ToString();
    }

    /// <summary>
    /// Addメソッドを生成する
    /// </summary>
    /// <param name="sb">StringBuilder</param>
    /// <param name="columnCount">列数</param>
    private static void GenerateAddMethod(StringBuilder sb, int columnCount)
    {
        // 型パラメータのリストを生成
        var typeParams = string.Join(", ", Enumerable.Range(1, columnCount).Select(i => $"T{i}"));
        
        // パラメータのリストを生成
        var parameters = string.Join(",\n        ", Enumerable.Range(1, columnCount)
            .Select(i => $"(Column<T{i}> Col, T{i} Val) c{i}"));
        
        // AddRowの引数のリストを生成
        var addRowArgs = string.Join(", ", Enumerable.Range(1, columnCount)
            .Select(i => $"(c{i}.Col, c{i}.Val)"));

        // コメント
        sb.AppendLine($"    // {columnCount}列用");
        
        // メソッドシグネチャ
        sb.AppendLine($"    public void Add<{typeParams}>(");
        sb.AppendLine($"        {parameters})");
        sb.AppendLine("    {");
        
        // AddRow呼び出し
        sb.AppendLine($"        AddRow({addRowArgs});");
        sb.AppendLine("    }");
    }
}
