using System.Collections.Immutable;
using Microsoft.CodeAnalysis;

namespace AuraORM.Generators;

/// <summary>
/// Checks the <c>[ValueConverter]</c> declarations of a compilation and emits the module initializer that registers the
/// converters it declares and uses (<c>docs/design.ja.md</c> §3.6): one internal class
/// <c>AuraORM.Generated.__AuraValueConverters</c> per assembly.
/// </summary>
internal static class ConverterEmitter
{
    public const string RegistrationType = "AuraORM.Generated.__AuraValueConverters";

    /// <summary>
    /// Reads the converters that the attributes on one type declare.
    /// </summary>
    /// <param name="context">The context of a type with <c>[ValueConverter]</c>.</param>
    /// <returns>The valid converters and the diagnostics of the others.</returns>
    public static ParseResult<ConverterSet> ReadType(GeneratorAttributeSyntaxContext context)
    {
        var type = (ITypeSymbol)context.TargetSymbol;
        return Read(context.Attributes, type, context.SemanticModel.Compilation);
    }

    /// <summary>
    /// Reads the converters that the assembly attributes of the compilation declare.
    /// </summary>
    /// <param name="compilation">The compilation.</param>
    /// <returns>The valid converters and the diagnostics of the others.</returns>
    public static ParseResult<ConverterSet> ReadAssembly(Compilation compilation) =>
        Read(
            compilation.Assembly.GetAttributes().Where(a => a.AttributeClass?.ToDisplayString() == ConverterLookup.AttributeName).ToImmutableArray(),
            null,
            compilation
        );

    /// <summary>
    /// Returns the diagnostic of a type that has the name of the registration class, or <see langword="null"/> (AURA0116).
    /// </summary>
    /// <param name="compilation">The compilation.</param>
    /// <returns>The diagnostic, or <see langword="null"/>.</returns>
    public static DiagnosticInfo? CheckName(Compilation compilation)
    {
        INamedTypeSymbol? existing = compilation.Assembly.GetTypeByMetadataName(RegistrationType);
        return existing is null ? null : DiagnosticInfo.Create(Diagnostics.RegistrationCollision, existing.Locations.FirstOrDefault());
    }

    /// <summary>
    /// Emits the registration of the converters, or returns <see langword="null"/> when none can be named here.
    /// </summary>
    /// <param name="converters">The converters, possibly repeated.</param>
    /// <returns>The source, or <see langword="null"/>.</returns>
    public static string? Emit(IEnumerable<ConverterModel> converters)
    {
        List<ConverterModel> registered = converters.Where(c => c.IsAccessible).Distinct().OrderBy(c => c.ModelType, StringComparer.Ordinal).ToList();
        if (registered.Count == 0)
        {
            return null;
        }

        var w = new CodeWriter();
        w.Line("// <auto-generated/>");
        w.Line("#nullable enable");
        w.Line();
        w.Open("namespace AuraORM.Generated");
        w.Line("/// <summary>");
        w.Line("/// Registers the value converters that this assembly declares or uses (docs/design.ja.md §3.6).");
        w.Line("/// </summary>");
        w.Open("internal static class __AuraValueConverters");
        w.Line("[global::System.Runtime.CompilerServices.ModuleInitializer]");
        w.Open("internal static void Register()");
        foreach (ConverterModel converter in registered)
        {
            string method = converter.IsValueType ? "RegisterStruct" : "RegisterClass";
            w.Line(
                "global::AuraORM.ValueConverters."
                    + method
                    + "<"
                    + converter.ModelType
                    + ", "
                    + converter.ProviderType
                    + ", "
                    + converter.ConverterType
                    + ">();"
            );
        }

        w.Close();
        w.Close();
        w.Close();
        return w.ToString();
    }

    private static ParseResult<ConverterSet> Read(ImmutableArray<AttributeData> attributes, ITypeSymbol? annotated, Compilation compilation)
    {
        var models = new List<ConverterModel>();
        var diagnostics = new List<DiagnosticInfo>();
        foreach (AttributeData attribute in attributes)
        {
            Location? location = attribute.ApplicationSyntaxReference?.GetSyntax().GetLocation();
            if (ConverterLookup.ConverterOf(attribute) is not { } converter)
            {
                continue;
            }

            if (ConverterLookup.Check(converter, annotated, out ConverterModel? model) is { } reason)
            {
                diagnostics.Add(DiagnosticInfo.Create(Diagnostics.InvalidConverter, location, converter.ToDisplayString(), reason));
                continue;
            }

            // §3.6: the registration that this compilation emits names the converter and the model.
            if (!model!.IsAccessible)
            {
                diagnostics.Add(
                    DiagnosticInfo.Create(
                        Diagnostics.InvalidConverter,
                        location,
                        converter.ToDisplayString(),
                        "it or its model type is not reachable from the generated registration; make both public or internal"
                    )
                );
                continue;
            }

            // §3.6: a type has one converter among the declarations that it sees.
            ITypeSymbol modelType =
                annotated ?? converter.AllInterfaces.First(i => i.TypeArguments.Length == 2 && i.Name == "IValueConverter").TypeArguments[0];
            if (
                !ConverterLookup.TryResolve(modelType, compilation, out _, out (DiagnosticDescriptor Descriptor, string[] Arguments)? error)
                && error is { } e
                && e.Descriptor.Id == Diagnostics.DuplicateConverter.Id
            )
            {
                diagnostics.Add(DiagnosticInfo.Create(e.Descriptor, location, e.Arguments));
                continue;
            }

            models.Add(model!);
        }

        return new ParseResult<ConverterSet>(
            new ConverterSet(new EquatableArray<ConverterModel>(models.ToImmutableArray())),
            new EquatableArray<DiagnosticInfo>(diagnostics.ToImmutableArray())
        );
    }
}

/// <summary>
/// The converters that one declaration reads.
/// </summary>
/// <param name="Converters">The converters.</param>
internal sealed record ConverterSet(EquatableArray<ConverterModel> Converters);
