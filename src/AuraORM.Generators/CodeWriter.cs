using System.Text;

namespace AuraORM.Generators;

/// <summary>
/// Writes indented C# source.
/// </summary>
internal sealed class CodeWriter
{
    private readonly StringBuilder _builder = new();
    private int _indent;

    public void Line(string text = "")
    {
        if (text.Length > 0)
        {
            _builder.Append(' ', _indent * 4);
            _builder.Append(text);
        }

        _builder.Append('\n');
    }

    public void Open(string text)
    {
        Line(text);
        Line("{");
        _indent++;
    }

    public void Close(string suffix = "")
    {
        _indent--;
        Line("}" + suffix);
    }

    /// <summary>
    /// Writes the file header and opens the namespace and the partial types that contain the target.
    /// </summary>
    /// <param name="target">The target type.</param>
    /// <param name="baseList">The base list to add to the type's declaration, such as <c> : global::AuraORM.IQueryResult&lt;User&gt;</c>.</param>
    /// <returns>The number of types opened, for <see cref="EndTarget"/>.</returns>
    public int BeginTarget(TypeTarget target, string baseList)
    {
        Line("// <auto-generated/>");
        Line("#nullable enable");
        Line();
        if (target.Namespace is not null)
        {
            Line("namespace " + target.Namespace + ";");
            Line();
        }

        foreach (string container in target.Containers)
        {
            Open(container);
        }

        Open(target.Declaration + baseList);
        return target.Containers.Count + 1;
    }

    public void EndTarget(int opened)
    {
        for (int i = 0; i < opened; i++)
        {
            Close();
        }
    }

    public override string ToString() => _builder.ToString();
}
