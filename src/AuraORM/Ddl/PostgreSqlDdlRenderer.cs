using System.Globalization;
using System.Text;

namespace AuraORM;

/// <summary>
/// The DDL of PostgreSQL (design §13).
/// </summary>
internal sealed class PostgreSqlDdlRenderer(DialectRenderer sql) : DdlRenderer(sql)
{
    // §13.2: BY DEFAULT, because ALWAYS requires OVERRIDING SYSTEM VALUE on an INSERT that sets the column.
    protected override string AutoIncrement => "GENERATED BY DEFAULT AS IDENTITY";

    protected override string TypeName(ColumnInfo column) =>
        column.Type switch
        {
            ColumnType.Boolean => "boolean",
            ColumnType.Byte or ColumnType.Int16 => "smallint",
            ColumnType.Int32 => "integer",
            ColumnType.Int64 => "bigint",
            ColumnType.Single => "real",
            ColumnType.Double => "double precision",
            ColumnType.Decimal => string.Format(CultureInfo.InvariantCulture, "numeric({0},{1})", column.Precision, column.Scale),
            ColumnType.String => column.MaxLength is { } n ? "varchar(" + n.ToString(CultureInfo.InvariantCulture) + ")" : "text",
            ColumnType.Binary => "bytea",
            ColumnType.Guid => "uuid",
            ColumnType.DateTime => "timestamp",
            ColumnType.DateTimeOffset => "timestamp with time zone",
            ColumnType.DateOnly => "date",
            _ => "time",
        };

    // §13.3: CURRENT_TIMESTAMP is timestamptz; in a timestamp column it would be the session's local time.
    protected override string CurrentTimestamp(ColumnType type) =>
        type == ColumnType.DateTimeOffset ? "CURRENT_TIMESTAMP" : "(CURRENT_TIMESTAMP AT TIME ZONE 'UTC')";

    // §13.6: an index is created in the schema of its table, and DROP INDEX names it with that schema.
    protected override void WriteDropIndexTarget(SqlWriter writer, TableInfo table, string index) => WriteTableName(writer, table.Schema, index);

    // §13.7: varchar(n) and numeric(p, s) (PostgreSQL's errors at 10485761 and 1001).
    protected override int? MaxStringLength => 10485760;

    protected override int? MaxPrecision => 1000;

    // §13.7: NAMEDATALEN - 1 bytes of UTF-8; a longer name is truncated without an error, so it is stopped here.
    protected override string? CheckNameLength(string name) =>
        Encoding.UTF8.GetByteCount(name) > 63
            ? "is longer than the 63 bytes of UTF-8 that PostgreSQL keeps of a name; PostgreSQL would truncate it without an error."
            : null;
}
